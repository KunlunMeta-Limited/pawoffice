import assert from 'node:assert/strict'
import { readFile, mkdir } from 'node:fs/promises'
import { chromium, expect } from '@playwright/test'
import { createServer } from 'vite'
import { createPawOfficeServer } from '../../server/dist/app.js'
import { createWorkflowMock } from '../../integration/clients/workflow-mock.mjs'

const app = await createPawOfficeServer({ officeRequestMs: 5000 })
let mock, vite, browser
await mkdir('test-results/result-workspace', { recursive: true })
try {
  const relay = await app.listen({ host: '127.0.0.1', port: 0 })
  mock = createWorkflowMock({ baseUrl: relay, scenario: 'ecommerce', mode: 'showcase' })
  const mockUrl = await mock.app.listen({ host: '127.0.0.1', port: 0 })
  await mock.initialize(mockUrl)
  process.env.PAWOFFICE_INTERNAL_API_URL = relay
  vite = await createServer({ configFile: 'vite.config.ts', server: { host: '127.0.0.1', port: 0, open: false } })
  await vite.listen()
  browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'], reducedMotion: 'reduce' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(vite.resolvedUrls.local[0])
  await page.getByRole('textbox', { name: '给办公室发送消息' }).click()
  await page.getByRole('tab', { name: '成果预览 · 代码 / CSV / JSON', exact: true }).click()
  await page.getByRole('button', { name: '收起聊天', exact: true }).click()
  await page.getByRole('button', { name: /查看当前成果/ }).click()
  const reader = page.getByRole('dialog', { name: '成果阅读器', exact: true })
  await reader.getByRole('tab', { name: '交付物', exact: true }).click()
  const fixture = mock.office.conversations.find(item => item.id === 'attachments').whiteboard
  const open = async title => {
    await reader.locator('.result-artifact:visible').filter({ has: page.getByRole('heading', { name: title, exact: true }) }).getByRole('button', { name: '查看', exact: true }).click()
    return page.getByRole('dialog', { name: title, exact: true })
  }
  const json = await open('上市配置.json')
  await expect(json.getByRole('region', { name: 'JSON树', exact: true })).toContainText('123456789012345678901')
  await expect(json).toContainText('1800')
  await json.getByRole('button', { name: '全部收起', exact: true }).click()
  await expect(json.locator('.result-json-children')).toHaveCount(0)
  await json.getByRole('button', { name: '展开顶层', exact: true }).click()
  await json.locator('summary').filter({ hasText: 'review' }).click()
  await expect(json.getByRole('region', { name: 'JSON树' })).toContainText('null')
  await json.getByLabel('文档版本').selectOption('attachments-config-v1')
  await expect(json.getByRole('region', { name: 'JSON树' })).toContainText('3000')
  await json.getByRole('button', { name: '源文', exact: true }).click()
  await json.getByRole('button', { name: '复制源文', exact: true }).click()
  await expect.poll(() => page.evaluate(async () => (await navigator.clipboard.readText()).replace(/\r\n/g, '\n'))).toBe(fixture.deliveries[0].result.artifacts.find(item => item.id === 'attachments-config').content)
  await json.getByRole('button', { name: '与当前版本比较', exact: true }).click()
  await expect(json.locator('tr[data-kind=added]')).toContainText([/1800/])
  await page.keyboard.press('Escape')

  const csv = await open('搜索词观察明细.csv')
  const table = csv.getByRole('table', { name: 'CSV数据', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(25)
  await expect(table).toContainText('00001')
  await expect(table).toContainText('客户反馈：轻便,易收纳\n需要补充尺寸图')
  await csv.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(table).toContainText('00026')
  await csv.getByRole('searchbox', { name: '搜索CSV内容' }).fill('00065')
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(table).toContainText('00065')
  await csv.getByRole('checkbox', { name: '首行为表头' }).uncheck()
  await expect(table.locator('thead')).toContainText('第1列')
  await csv.getByRole('searchbox', { name: '搜索CSV内容' }).fill('')
  await csv.getByRole('checkbox', { name: '首行为表头' }).check()
  const event = page.waitForEvent('download')
  await csv.getByRole('button', { name: '下载该版本', exact: true }).click()
  assert.equal(await readFile(await (await event).path(), 'utf8'), fixture.result.artifacts.find(item => item.id === 'attachments-observations').content)
  await page.screenshot({ path: 'test-results/result-workspace/csv-preview.png' })
  await page.keyboard.press('Escape')

  const code = await open('预算核对示例.ts')
  await expect(code.locator('.hljs-keyword').first()).toBeVisible()
  await expect(code.getByLabel('代码内容')).not.toContainText('requiresMerchantAuthorization')
  await code.getByRole('button', { name: /展开全部/ }).click()
  await expect(code.getByLabel('代码内容')).toContainText('requiresMerchantAuthorization')
  await code.getByRole('button', { name: '复制源文', exact: true }).click()
  await expect.poll(() => page.evaluate(async () => (await navigator.clipboard.readText()).replace(/\r\n/g, '\n'))).toBe(fixture.result.artifacts.find(item => item.id === 'attachments-code').content)
  await code.getByRole('button', { name: '自动换行', exact: true }).click()
  await expect(code.getByLabel('代码内容')).toHaveAttribute('data-wrap', 'true')
  await page.screenshot({ path: 'test-results/result-workspace/code-preview.png' })
  await page.keyboard.press('Escape')
  const jsonAgain = await open('上市配置.json')
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.screenshot({ path: 'test-results/result-workspace/json-preview-mobile.png' })
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await reader.getByRole('tab', { name: '概览', exact: true }).click()
  const notes = reader.getByRole('region', { name: '使用说明与代码片段', exact: true })
  await expect(notes.locator('.hljs-keyword').first()).toBeVisible()
  await expect(notes.locator('.mermaid-diagram-svg svg')).toHaveCount(1)

  await reader.getByRole('tab', { name: '交付物', exact: true }).click()
  fixture.result.artifacts.push({ id: 'bad-json', versionId: 'bad-json-v1', title: '无效配置.json', mimeType: 'application/json', content: '{"x":}' },
    { id: 'bad-csv', versionId: 'bad-csv-v1', title: '无效表格.csv', mimeType: 'text/csv', content: 'a,b\n1,"not closed' },
    { id: 'structured-report', versionId: 'structured-report-v1', title: '结构化经营摘要' })
  fixture.result.sections.push({ kind: 'custom', id: 'structured-summary', title: '经营摘要', purpose: 'artifact-preview', artifactId: 'structured-report', versionId: 'structured-report-v1', blocks: [{ type: 'text', text: '这份报告以结构化内容交付，无需创建实体文件。' }] })
  mock.office.seq++
  await mock.initialize(mockUrl)
  const structured = await open('结构化经营摘要')
  await expect(structured.getByLabel('文件内容预览')).toContainText('无需创建实体文件')
  await expect(structured.getByRole('button', { name: '未提供原件', exact: true })).toBeDisabled()
  await expect(structured.getByRole('alert')).toHaveCount(0)
  await expect(structured).not.toContainText('SHA-256 校验通过')
  await page.keyboard.press('Escape')
  const invalid = await open('无效配置.json')
  await expect(invalid.getByRole('alert')).toContainText('JSON格式不正确')
  await invalid.getByRole('button', { name: '源文', exact: true }).click()
  await expect(invalid.getByLabel('代码内容')).toHaveText('{"x":}')
  await page.keyboard.press('Escape')
  const invalidCsv = await open('无效表格.csv')
  await expect(invalidCsv.getByRole('alert')).toContainText('CSV引号格式不正确')
  await invalidCsv.getByRole('button', { name: '源文', exact: true }).click()
  await expect(invalidCsv.getByLabel('代码内容')).toContainText('not closed')
  await page.keyboard.press('Escape')
  await reader.getByRole('button', { name: '关闭当前成果' }).click()
  await page.reload()
  await page.getByRole('button', { name: /查看当前成果/ }).click()
  await reader.getByRole('tab', { name: '交付物', exact: true }).click()
  await open('上市配置.json')
  await expect(jsonAgain.getByRole('region', { name: 'JSON树' })).toContainText('1800')
  assert.deepEqual(errors, [])
  console.log('Passed file previews: real backend versions, exact large integers, JSON tree/source/diff, CSV quoting/search/pagination/original download, code highlight/copy/fold, Markdown and Mermaid, invalid inputs, reload and mobile.')
} finally {
  await browser?.close(); await vite?.close(); await mock?.app.close(); await app.close()
}
