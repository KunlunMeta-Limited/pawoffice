export function normalizeDemoQuestion(text: string) {
  return text.normalize('NFKC').toLowerCase().replace(/[\p{P}\s]/gu, '')
}

const startPhrases = ['开始', '开始处理', '开始执行', '开始演示', '重新演示', '重跑一遍']

export function isDemoStartCommand(question: string, extraPhrases: readonly string[] = []) {
  const command = question.replace(/^(?:请|麻烦)(?:你|帮我)?/, '').replace(/(?:一下|吧)+$/, '')
  return startPhrases.includes(command) || extraPhrases.includes(command)
}

export function matchesDemoKeyword(question: string, keywords: readonly string[]) {
  return keywords.some(keyword => question.includes(keyword))
}
