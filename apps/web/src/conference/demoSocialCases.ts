const account = '一平米办公笔记'
const audience = '租房办公、宿舍学习和小桌面用户；想把桌面用顺手，不追求整套换新。内容以可核对的尺寸、步骤和取舍为主。'

function socialCase(input: Omit<DemoCase, 'items' | 'editorial'> & { plan: Omit<EditorialPlan, 'account' | 'audience'> }): DemoCase {
  const { plan, ...base } = input
  return { ...base, editorial: { account, audience, ...plan }, items: plan.drafts.map(draft => ({
    label: draft.platform, status: '待审核',
    detail: `${draft.format}《${draft.title}》已起草；${draft.pages.length ? `${draft.pages.length} 页配图分镜待制作。` : '采用纯文字形式。'}${draft.review}`,
    source: draft.sourceIds.map(id => { const source = plan.sources.find(item => item.id === id); return `${id} ${source?.title ?? ''}` }).join('；'),
  })) }
}

